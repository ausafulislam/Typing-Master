-- TypeMaster schema for Supabase (Postgres)
-- Idempotent: safe to run multiple times.
-- Run this in Supabase Dashboard -> SQL Editor.

-- 1. Table
create table if not exists public.game_sessions (
  id bigint generated by default as identity primary key,
  name text not null,
  duration integer,
  wpm integer,
  accuracy numeric,
  errors integer,
  created_at timestamptz default now()
);

-- 2. One row per player name (prevents duplicate leaderboard entries under concurrency).
-- NOTE: if you already have duplicate names, run a cleanup first:
--   delete from public.game_sessions a using public.game_sessions b
--   where a.name = b.name and a.id < b.id;
create unique index if not exists game_sessions_name_unique on public.game_sessions (name);

-- 3. Row Level Security: only the policies below can touch this table.
alter table public.game_sessions enable row level security;

drop policy if exists "Allow public select" on public.game_sessions;
create policy "Allow public select" on public.game_sessions
  for select using (true);

drop policy if exists "Allow public insert" on public.game_sessions;
create policy "Allow public insert" on public.game_sessions
  for insert with check (true);

drop policy if exists "Allow public update" on public.game_sessions;
create policy "Allow public update" on public.game_sessions
  for update using (true) with check (true);
